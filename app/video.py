"""FFmpeg / FFprobe helpers: validation, audio extraction and frame sampling.

All subprocess calls use argument lists (never ``shell=True``) and absolute
paths generated by the server, so user input never reaches a shell.
"""

from __future__ import annotations

import json
import shutil
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

from PIL import Image, ImageStat

from .config import settings


class MediaError(Exception):
    """Raised for invalid media or failed FFmpeg operations (message is user-safe)."""


@dataclass
class MediaInfo:
    duration: float
    width: int
    height: int
    video_codec: str
    audio_codec: str | None
    format_name: str
    size_bytes: int

    @property
    def has_audio(self) -> bool:
        return self.audio_codec is not None


@dataclass
class Frame:
    path: Path
    timestamp: float
    brightness: float = 0.0
    hash_bits: int = field(default=0, repr=False)
    mean_rgb: tuple[float, float, float] = field(default=(0.0, 0.0, 0.0), repr=False)


def ffmpeg_available() -> dict[str, str | None]:
    """Return the version line of ffmpeg/ffprobe, or None when missing."""
    out: dict[str, str | None] = {}
    for exe in ("ffmpeg", "ffprobe"):
        path = shutil.which(exe)
        if not path:
            out[exe] = None
            continue
        try:
            res = subprocess.run([path, "-version"], capture_output=True, text=True, timeout=10)
            out[exe] = res.stdout.splitlines()[0] if res.stdout else path
        except (OSError, subprocess.SubprocessError):
            out[exe] = None
    return out


def _run(args: list[str], timeout: int | None = None) -> subprocess.CompletedProcess:
    exe = shutil.which(args[0])
    if not exe:
        raise MediaError(f"{args[0]} không được cài đặt trên máy chủ.")
    try:
        return subprocess.run(
            [exe, *args[1:]],
            capture_output=True,
            timeout=timeout or settings.ffmpeg_timeout_sec,
            check=False,
        )
    except subprocess.TimeoutExpired as exc:
        raise MediaError(f"{args[0]} xử lý quá thời gian cho phép.") from exc


def probe(path: Path) -> MediaInfo:
    """Inspect a media file with ffprobe."""
    res = _run(
        ["ffprobe", "-v", "error", "-print_format", "json", "-show_format", "-show_streams", str(path)],
        timeout=30,
    )
    if res.returncode != 0:
        raise MediaError("Không đọc được tệp video (tệp hỏng hoặc không phải video hợp lệ).")
    try:
        data = json.loads(res.stdout.decode("utf-8", "replace"))
    except json.JSONDecodeError as exc:
        raise MediaError("Không phân tích được thông tin video.") from exc

    streams = data.get("streams", [])
    video = next((s for s in streams if s.get("codec_type") == "video"), None)
    audio = next((s for s in streams if s.get("codec_type") == "audio"), None)
    if video is None:
        raise MediaError("Tệp không chứa luồng hình ảnh (video stream).")

    fmt = data.get("format", {})
    try:
        duration = float(fmt.get("duration") or video.get("duration") or 0)
    except (TypeError, ValueError):
        duration = 0.0

    return MediaInfo(
        duration=duration,
        width=int(video.get("width") or 0),
        height=int(video.get("height") or 0),
        video_codec=str(video.get("codec_name") or "unknown"),
        audio_codec=str(audio.get("codec_name")) if audio else None,
        format_name=str(fmt.get("format_name") or ""),
        size_bytes=int(fmt.get("size") or path.stat().st_size),
    )


def validate(path: Path) -> MediaInfo:
    """Check container, size, duration and streams against configured limits."""
    size = path.stat().st_size
    if size == 0:
        raise MediaError("Tệp tải lên rỗng.")
    if size > settings.max_upload_bytes:
        raise MediaError(f"Tệp vượt quá {settings.max_upload_mb} MB.")

    info = probe(path)
    # ffprobe reports MP4 as "mov,mp4,m4a,3gp,3g2,mj2".
    if "mp4" not in info.format_name:
        raise MediaError("Chỉ hỗ trợ định dạng MP4.")
    if info.duration <= 0:
        raise MediaError("Không xác định được thời lượng video.")
    if info.duration > settings.max_duration_sec:
        raise MediaError(
            f"Video dài {info.duration / 60:.1f} phút, vượt giới hạn {settings.max_duration_sec / 60:.0f} phút."
        )
    if not info.has_audio:
        raise MediaError("Video không có âm thanh nên không thể chuyển thành văn bản.")
    return info


def extract_audio(video: Path, out_wav: Path) -> Path:
    """Extract mono 16 kHz PCM audio, the format Whisper expects."""
    out_wav.parent.mkdir(parents=True, exist_ok=True)
    res = _run(
        ["ffmpeg", "-nostdin", "-y", "-v", "error", "-i", str(video),
         "-vn", "-ac", "1", "-ar", "16000", "-c:a", "pcm_s16le", str(out_wav)]
    )
    if res.returncode != 0 or not out_wav.exists() or out_wav.stat().st_size == 0:
        raise MediaError("Không tách được âm thanh từ video.")
    return out_wav


def _average_hash(img: Image.Image, size: int = 8) -> int:
    small = img.convert("L").resize((size, size), Image.Resampling.BILINEAR)
    pixels = list(small.tobytes())
    avg = sum(pixels) / len(pixels)
    bits = 0
    for p in pixels:
        bits = (bits << 1) | (1 if p >= avg else 0)
    return bits


def _hamming(a: int, b: int) -> int:
    return bin(a ^ b).count("1")


def _is_duplicate(a: Frame, b: Frame) -> bool:
    """Same structure (perceptual hash) and same overall colour => same shot."""
    color_dist = sum((x - y) ** 2 for x, y in zip(a.mean_rgb, b.mean_rgb)) ** 0.5
    return _hamming(a.hash_bits, b.hash_bits) <= 6 and color_dist < 20


def extract_frames(
    video: Path,
    out_dir: Path,
    duration: float,
    max_frames: int | None = None,
    candidates: int | None = None,
) -> list[Frame]:
    """Sample candidate frames evenly, then drop dark, flat and near-duplicate ones.

    Each candidate is grabbed with a fast input seek, so cost is proportional to
    the number of candidates rather than the video length.
    """
    max_frames = max_frames or settings.max_frames
    candidates = candidates or max_frames * 2
    out_dir.mkdir(parents=True, exist_ok=True)

    frames: list[Frame] = []
    # Skip the very first/last seconds, which are often black or title cards.
    margin = min(2.0, duration * 0.05)
    span = max(duration - 2 * margin, 0.1)
    for i in range(candidates):
        ts = margin + span * (i + 0.5) / candidates
        target = out_dir / f"cand_{i:02d}.jpg"
        res = _run(
            ["ffmpeg", "-nostdin", "-y", "-v", "error", "-ss", f"{ts:.2f}", "-i", str(video),
             "-frames:v", "1", "-vf", f"scale='min({settings.frame_width},iw)':-2",
             "-q:v", "4", str(target)],
            timeout=60,
        )
        if res.returncode != 0 or not target.exists():
            continue
        with Image.open(target) as img:
            stat = ImageStat.Stat(img.convert("L"))
            frames.append(
                Frame(path=target, timestamp=round(ts, 2), brightness=stat.mean[0], hash_bits=_average_hash(img),
                      mean_rgb=tuple(ImageStat.Stat(img.convert("RGB")).mean))
            )
            # Very low variance means a blank/solid screen.
            if stat.stddev[0] < 8:
                frames[-1].brightness = 0

    kept: list[Frame] = []
    for f in frames:
        if f.brightness < 20 or f.brightness > 245:
            continue
        if any(_is_duplicate(f, k) for k in kept):
            continue
        kept.append(f)

    if len(kept) > max_frames:
        # Keep an even spread across the timeline.
        step = len(kept) / max_frames
        kept = [kept[int(i * step)] for i in range(max_frames)]

    keep_paths = {f.path for f in kept}
    for f in frames:
        if f.path not in keep_paths:
            f.path.unlink(missing_ok=True)

    final: list[Frame] = []
    for idx, f in enumerate(kept):
        new_path = out_dir / f"frame_{idx:02d}.jpg"
        f.path.replace(new_path)
        _compress(new_path)
        f.path = new_path
        final.append(f)
    return final


def _compress(path: Path, max_width: int | None = None, quality: int = 82) -> None:
    max_width = max_width or settings.frame_width
    with Image.open(path) as img:
        img = img.convert("RGB")
        if img.width > max_width:
            ratio = max_width / img.width
            img = img.resize((max_width, int(img.height * ratio)), Image.Resampling.LANCZOS)
        img.save(path, "JPEG", quality=quality, optimize=True, progressive=True)
